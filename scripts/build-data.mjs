// Regenerates data.js from Riot's Data Dragon.
// Usage: node scripts/build-data.mjs [path/to/item.json]
// Without a path it downloads the latest patch's item.json.
import { readFileSync, writeFileSync } from "node:fs";

const slug = (s) => s.toLowerCase().replace(/['’.]/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

let raw, version;
if (process.argv[2]) {
  raw = JSON.parse(readFileSync(process.argv[2], "utf8"));
  version = raw.version;
} else {
  version = (await (await fetch("https://ddragon.leagueoflegends.com/api/versions.json")).json())[0];
  raw = await (await fetch(`https://ddragon.leagueoflegends.com/cdn/${version}/data/en_US/item.json`)).json();
}
const d = raw.data;
const ok = (id) => {
  const i = d[id];
  return i && i.maps?.["11"] && i.gold.purchasable && i.inStore !== false && !i.requiredChampion && !i.requiredAlly && !i.hideFromAll;
};

const finals = Object.entries(d).filter(([id, i]) =>
  ok(id) && i.from?.length >= 2 && !(i.into?.length) && (i.depth || 0) >= 2 && i.gold.total >= 2000 && +id < 10000);

const componentIds = new Set(finals.flatMap(([, i]) => i.from));
// Also let any purchasable SR component be used as an imposter.
for (const [id, i] of Object.entries(d)) {
  if (ok(id) && i.into?.some((x) => finals.some(([f]) => f === x))) componentIds.add(id);
}

const pick = (id) => ({ id, name: d[id].name, slug: slug(d[id].name), cost: d[id].gold.total, tags: d[id].tags || [] });
const seen = new Set(); // some items exist twice under different ids (e.g. Tear of the Goddess)
const components = [...componentIds].filter((id) => !seen.has(d[id].name) && seen.add(d[id].name)).map(pick).sort((a, b) => a.name.localeCompare(b.name));
const items = finals.map(([id, i]) => ({ ...pick(id), from: i.from })).sort((a, b) => a.name.localeCompare(b.name));

const out = `// Auto-generated by scripts/build-data.mjs from Data Dragon ${version}. Do not edit by hand.
window.GAME_DATA = ${JSON.stringify({ version, components, items }, null, 1)};
`;
writeFileSync(new URL("../data.js", import.meta.url), out);

const md = [`# Images needed (patch ${version})`, "",
  "Put every image in `assets/items/` as a **PNG named exactly as below** (square, 64×64 or bigger).",
  "Any missing image falls back to a lettered placeholder, so the game works before you add them.", "",
  `## Components (${components.length})`, "", ...components.map((c) => `- [ ] \`${c.slug}.png\` — ${c.name}`), "",
  `## Finished items (${items.length})`, "", ...items.map((c) => `- [ ] \`${c.slug}.png\` — ${c.name}`), ""].join("\n");
writeFileSync(new URL("../IMAGES.md", import.meta.url), md);
console.log(`patch ${version}: ${components.length} components, ${items.length} items`);
